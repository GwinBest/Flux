        case HttpField::ContentLanguage:               return "Content-Language";
        case HttpField::ContentLength:                 return "Content-Length";
        case HttpField::ContentLocation:               return "Content-Location";
        case HttpField::ContentRange:                  return "Content-Range";
        case HttpField::ContentSecurityPolicy:         return "Content-Security-Policy";
        case HttpField::ContentSecurityPolicyReportOnly:
            return "Content-Security-Policy-Report-Only";
        case HttpField::ContentType:                    return "Content-Type";
        case HttpField::Cookie:                         return "Cookie";
        case HttpField::CrossOriginEmbedderPolicy:      return "Cross-Origin-Embedder-Policy";
        case HttpField::CrossOriginOpenerPolicy:        return "Cross-Origin-Opener-Policy";
        case HttpField::CrossOriginResourcePolicy:      return "Cross-Origin-Resource-Policy";
        case HttpField::Date:                           return "Date";
        case HttpField::Deprecation:                    return "Deprecation";
        case HttpField::DeviceMemory:                   return "Device-Memory";
