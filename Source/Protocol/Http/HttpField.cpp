        case HttpField::Host:                           return "Host";
        case HttpField::HTTP2Settings:                  return "HTTP2-Settings";
        case HttpField::IfMatch:                        return "If-Match";
        case HttpField::IfModifiedSince:                return "If-Modified-Since";
